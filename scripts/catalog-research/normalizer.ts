export function normalizeColours(text?: string): string[] {
  if (!text) return [];
  const found = new Set<string>();
  for (const [re, norm] of COLOUR_MAP) {
    if (re.test(text)) found.add(norm);
    if (found.size >= 3) break;
  }
  return [...found];
}

export function normalizeMaterials(text?: string): string[] {
  if (!text) return [];
  const found = new Set<string>();
  for (const [re, norm] of MATERIAL_MAP) {
    if (re.test(text)) found.add(norm);
    if (found.size >= 4) break;
  }
  return [...found];
}

const DIM_RE =
  /(\d{1,4}(?:[.,]\d{1,2})?)\s?(?:x|×|\*|by)\s?(\d{1,4}(?:[.,]\d{1,2})?)(?:\s?(?:x|×|\*|by)\s?(\d{1,4}(?:[.,]\d{1,2})?))?\s?(mm|cm|m|")?/i;

export function normalizeDimensions(text?: string): NormalizedCandidate['normalized']['dims'] | undefined {
  if (!text) return undefined;
  const m = text.match(DIM_RE);
  if (!m) return undefined;
  const unit = (m[4] ?? 'cm').toLowerCase();
  const toCm = (v: string) => {
    let n = parseFloat(v.replace(',', '.'));
    if (!Number.isFinite(n)) return undefined;
    if (unit === 'mm') n = n / 10;
    if (unit === 'm') n = n * 100;
    if (unit === '"') n = n * 2.54;
    return Math.round(n * 10) / 10;
  };
  const l = toCm(m[1]);
  const w = toCm(m[2]);
  const h = m[3] ? toCm(m[3]) : undefined;
  if (l === undefined || w === undefined) return undefined;
  return { length: l, width: w, height: h, unit: 'cm' };
}

export function normalizeWeight(text?: string): number | undefined {
  if (!text) return undefined;
  const kg = text.match(/(\d{1,3}(?:[.,]\d{1,2})?)\s?kg/i);
  if (kg) return parseFloat(kg[1].replace(',', '.'));
  const g = text.match(/(\d{1,5})\s?g\b/i);
  if (g) return Math.round((parseInt(g[1], 10) / 1000) * 100) / 100;
  return undefined;
}

const ELECTRICAL_RE = /lamp|light|led|luminaire|pendant|chandelier|spot|smart (light|plug|bulb)|electrical|plug.?in|rechargeable|usb/i;
const BATTERY_RE = /battery|solar|rechargeable|cordless|wireless|akku|batterie/i;

export interface NormalizeInput {
    sourceKey: string;
    sourceUrl: string;
    sourceProductId?: string;
    sourceProductName?: string;
    sourceBrand?: string;
    sourceDescription?: string;
    price?: string;
    currency?: string;
    availability?: string;
    sku?: string;
    gtin?: string;
    materials?: string;
    colours?: string;
    dimensions?: string;
    weight?: string;
    imageUrls?: string[];
    attributes?: Record<string, string>;
    extractionMethod: string;
    currencyHint?: string;
    categoryHint?: string;
  }

export function normalizeCandidate(
  candidate: {
    sourceKey: string;
    sourceUrl: string;
    sourceProductId?: string;
    sourceProductName?: string;
    sourceBrand?: string;
    sourceDescription?: string;
    price?: string;
    currency?: string;
    availability?: string;
    sku?: string;
    gtin?: string;
    materials?: string;
    colours?: string;
    dimensions?: string;
    weight?: string;
    imageUrls?: string[];
    attributes?: Record<string, string>;
    extractionMethod: string;
    currencyHint?: string;
    categoryHint?: string;
  },
): NormalizedCandidate | null {
  const name = (candidate.sourceProductName ?? '').trim();
  if (name.length < 3 || name.length > 220) return null;
  // Reject obviously non-product pages
  if (/checkout|cart|account|login|privacy|terms|cookie|robots\.txt|sitemap/i.test(candidate.sourceUrl)) return null;

  const { value: price, currency } = parsePrice(candidate.price, candidate.currencyHint ?? candidate.currency);
  const priceEur = price !== undefined ? toEur(price, currency) : undefined;
  const text = `${name} ${candidate.sourceDescription ?? ''} ${candidate.materials ?? ''}`;
  const dims = normalizeDimensions(candidate.dimensions ?? candidate.sourceDescription);

  return {
    sourceKey: candidate.sourceKey,
    sourceUrl: candidate.sourceUrl,
    sourceProductId: candidate.sourceProductId,
    sourceProductName: name,
    sourceBrand: candidate.sourceBrand,
    sourceDescription: candidate.sourceDescription?.slice(0, 800),
    sourcePrice: price,
    sourceSalePrice: undefined,
    sourceCurrency: currency,
    sourceAvailability: candidate.availability,
    sourceSku: candidate.sku,
    sourceGtin: candidate.gtin,
    sourceMaterials: candidate.materials,
    sourceColours: candidate.colours,
    sourceDimensions: candidate.dimensions,
    sourceWeight: candidate.weight,
    sourceImageUrls: (candidate.imageUrls ?? []).slice(0, 6),
    sourceAttributes: candidate.attributes ?? {},
    normalized: {
      nameClean: name
        .replace(/\s+/g, ' ')
        .replace(/[|–—].*$/, '')
        .trim()
        .slice(0, 120),
      priceEur,
      currencyOriginal: currency,
      materialsList: normalizeMaterials(`${candidate.materials ?? ''} ${candidate.sourceDescription ?? ''}`),
      coloursList: normalizeColours(candidate.colours ?? name),
      dims,
      weightKg: normalizeWeight(candidate.weight),
      categoryHint: candidate.categoryHint,
      isElectricalHint: ELECTRICAL_RE.test(text),
      isBatteryHint: BATTERY_RE.test(text),
    },
    extractionMethod: candidate.extractionMethod,
  };
}

/** Fingerprint for dedupe — normalized name + category + key attributes. */
export function fingerprint(n: NormalizedCandidate): string {
  const key = [n.normalized.nameClean.toLowerCase().replace(/[^a-z0-9]+/g, '-'), Math.round(n.normalized.priceEur ?? 0)]
    .join('|');
  return key;
}
