// ============================================================
// E-com.casa — Normalizer
// ------------------------------------------------------------
// Normalizes prices, currencies, dimensions, weights, colours,
// materials and names. Original source values are preserved in
// raw research records; normalization output feeds scoring and
// product generation only.
// ============================================================

export interface NormalizedCandidate {
  sourceKey: string;
  sourceUrl: string;
  sourceProductId?: string;
  sourceProductName: string;
  sourceBrand?: string;
  sourceDescription?: string;
  sourcePrice?: number;
  sourceSalePrice?: number;
  sourceCurrency: string;
  sourceAvailability?: string;
  sourceSku?: string;
  sourceGtin?: string;
  sourceMaterials?: string;
  sourceColours?: string;
  sourceDimensions?: string;
  sourceWeight?: string;
  sourceImageUrls: string[];
  sourceAttributes: Record<string, string>;
  normalized: {
    nameClean: string;
    priceEur?: number;
    currencyOriginal: string;
    materialsList: string[];
    coloursList: string[];
    dims?: { length?: number; width?: number; height?: number; depth?: number; diameter?: number; unit: string };
    weightKg?: number;
    categoryHint?: string;
    isElectricalHint: boolean;
    isBatteryHint: boolean;
  };
  extractionMethod: string;
}

const CURRENCY_SYMBOLS: Record<string, string> = {
  '€': 'EUR',
  '£': 'GBP',
  '$': 'USD',
};

/** FX reference rates for market-intelligence normalisation ONLY.
 *  Demo prices are generated by E-com.casa pricing logic — these are
 *  never presented as supplier costs. */
export const FX_TO_EUR: Record<string, number> = {
  EUR: 1,
  GBP: 1.17,
  USD: 0.92,
  DKK: 0.134,
  SEK: 0.087,
  PLN: 0.23,
  CZK: 0.04,
  HUF: 0.0025,
  RON: 0.2,
  BGN: 0.51,
};

export function parsePrice(raw?: string, currencyHint?: string): { value?: number; currency: string } {
  if (!raw) return { currency: currencyHint ?? 'EUR' };
  let currency = currencyHint ?? 'EUR';
  for (const [sym, code] of Object.entries(CURRENCY_SYMBOLS)) {
    if (raw.includes(sym)) currency = code;
  }
  const num = raw.replace(/[^\d.,]/g, '');
  if (!num) return { currency };
  // Handle "1.299,00" (EU) vs "1,299.00" (UK/US)
  let normalized: number;
  const lastComma = num.lastIndexOf(',');
  const lastDot = num.lastIndexOf('.');
  if (lastComma > lastDot) normalized = parseFloat(num.replace(/\./g, '').replace(',', '.'));
  else normalized = parseFloat(num.replace(/,/g, ''));
  if (!Number.isFinite(normalized) || normalized <= 0 || normalized > 100_000) return { currency };
  return { value: normalized, currency };
}

export function toEur(value: number, currency: string): number | undefined {
  const rate = FX_TO_EUR[currency];
  return rate ? Math.round(value * rate * 100) / 100 : undefined;
}

