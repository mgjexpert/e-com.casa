export const DICT: Record<Lang, Record<string, string>> = { en: EN, pt: PT };

/**
 * Translate a key for a language with `{var}` interpolation.
 * Falls back to English, then to the raw key (visible debugging cue).
 */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const dict = DICT[lang] ?? DICT.en;
  let text = dict[key] ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}
